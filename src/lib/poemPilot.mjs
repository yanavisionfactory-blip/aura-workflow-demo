export const POEM_TITLE = "When Tomorrow Opens";

export const POEM_TEXT = `Before the city remembered its name,
a ribbon of morning unfastened the blue.
Rain gathered softly against the pane,
each drop holding a world made new.

A paper boat sailed where the streetlights slept,
along a silver road left by the rain.
The sun found the promises we had kept
and warmed their small corners again.

If hope is a lantern, let it be bright
enough for the hands that are finding their way.
We'll carry its warmth through the last of the night
and give it away with the day.`;

